@_spi(SwiftGodotRuntimePrivate) import SwiftGodotRuntime

extension Autoload {
    /// Declares a Node subclass as an autoload. The name must be a unique identifier.
    public init<T: Node>(name: String, type: T.Type) {
        self.init(name: name, nodeType: type)
    }
}

extension Node {
    /// Finds an existing autoload. Returns nil before the node enters the scene tree.
    public static func autoload(named name: String) -> Self? {
        guard SwiftGodotAutoloads.isIdentifier(name),
              let tree = Engine.getMainLoop() as? SceneTree else {
            return nil
        }
        return tree.root.getNodeOrNull(path: NodePath("/root/\(name)")) as? Self
    }
}

/// Support used by `#initSwiftExtension` to install the autoload editor plugin.
public enum SwiftGodotAutoloads {
    public static func initialize<T: EditorPlugin>(pluginType: T.Type) {
        register(type: pluginType)
        editorAddPlugin(type: pluginType)
    }

    public static func deinitialize<T: EditorPlugin>(pluginType: T.Type) {
        editorRemovePlugin(type: pluginType)
        unregister(type: pluginType)
    }

    fileprivate static func isIdentifier(_ value: String) -> Bool {
        let bytes = Array(value.utf8)
        func isLetter(_ byte: UInt8) -> Bool {
            (65...90).contains(byte) || (97...122).contains(byte) || byte == 95
        }
        guard let first = bytes.first, isLetter(first) else { return false }
        return bytes.allSatisfy { isLetter($0) || (48...57).contains($0) }
    }

    /// Saves scenes and reconciles this extension's autoload settings in the editor.
    public static func synchronize(_ autoloads: [Autoload], owner: String, plugin: EditorPlugin) {
        guard isIdentifier(owner) else {
            GD.pushError("SwiftGodot autoload owner must be an identifier: \(owner)")
            return
        }
        let directory = "res://swiftgodot/autoloads/\(owner)"
        let manifestKey = "swiftgodot/autoloads/\(owner)"
        let marker = "; Generated by SwiftGodot. Changes will be replaced.\n"
        var names = Set<String>()

        // Check the complete declaration before changing files or settings.
        for entry in autoloads {
            guard SwiftGodotAutoloads.isIdentifier(entry.name), names.insert(entry.name).inserted else {
                GD.pushError("SwiftGodot autoload name must be a unique identifier: \(entry.name)")
                return
            }
            guard entry.nodeType.classInitializationLevel == .scene,
                  ClassDB.classExists(class: StringName(String(describing: entry.nodeType))),
                  !ClassDB.classExists(class: StringName(entry.name)) else {
                GD.pushError("SwiftGodot autoload requires a registered scene type and a name different from any class: \(entry.name)")
                return
            }
            let path = "\(directory)/\(entry.name).tscn"
            let setting = ProjectSettings.getSetting(name: "autoload/\(entry.name)", defaultValue: nil)
            if let setting, String(setting) != "*\(path)" {
                GD.pushError("SwiftGodot will not replace an existing autoload: \(entry.name)")
                return
            }
            if FileAccess.fileExists(path: path), !FileAccess.getFileAsString(path: path).hasPrefix(marker) {
                GD.pushError("SwiftGodot will not replace an existing scene: \(path)")
                return
            }
        }

        if !autoloads.isEmpty {
            let error = DirAccess.makeDirRecursiveAbsolute(path: directory)
            guard error == .ok else {
                GD.pushError("Cannot create SwiftGodot autoload directory: \(error)")
                return
            }
        }

        // Write scene text. Godot creates editor instances when entries are added.
        for entry in autoloads {
            let path = "\(directory)/\(entry.name).tscn"
            let scene = marker + """
            [gd_scene format=3]

            [node name="\(entry.name)" type="\(String(describing: entry.nodeType))"]

            """
            if FileAccess.fileExists(path: path), FileAccess.getFileAsString(path: path) == scene { continue }
            guard let file = FileAccess.open(path: path, flags: .write) else {
                GD.pushError("Cannot write SwiftGodot autoload scene: \(path)")
                return
            }
            let stored = file.storeString(scene)
            file.close()
            guard stored else {
                GD.pushError("Cannot save SwiftGodot autoload scene: \(path)")
                return
            }
        }

        let previous = ProjectSettings.getSetting(name: manifestKey, defaultValue: nil).flatMap(String.init) ?? ""
        var settingsChanged = false
        for name in previous.split(separator: ",").map(String.init) where !names.contains(name) {
            guard isIdentifier(name) else { continue }
            let key = "autoload/\(name)"
            let path = "\(directory)/\(name).tscn"
            if let setting = ProjectSettings.getSetting(name: key, defaultValue: nil),
               String(setting) == "*\(path)" {
                plugin.removeAutoloadSingleton(name: name)
                settingsChanged = true
            }
            if FileAccess.fileExists(path: path), FileAccess.getFileAsString(path: path).hasPrefix(marker) {
                let error = DirAccess.removeAbsolute(path: path)
                if error != .ok {
                    GD.pushError("Cannot remove unused SwiftGodot autoload scene: \(path)")
                }
            }
        }
        for entry in autoloads where !ProjectSettings.hasSetting(name: "autoload/\(entry.name)") {
            plugin.addAutoloadSingleton(name: entry.name, path: "\(directory)/\(entry.name).tscn")
            guard ProjectSettings.hasSetting(name: "autoload/\(entry.name)") else {
                GD.pushError("Godot rejected the SwiftGodot autoload name: \(entry.name)")
                return
            }
            settingsChanged = true
        }

        // Reuse this group's order positions to preserve unrelated autoload entries.
        let positions = autoloads.map { ProjectSettings.getOrder(name: "autoload/\($0.name)") }.sorted()
        for (entry, position) in zip(autoloads, positions) {
            let key = "autoload/\(entry.name)"
            if ProjectSettings.getOrder(name: key) != position {
                ProjectSettings.setOrder(name: key, position: position)
                settingsChanged = true
            }
        }
        let manifest = autoloads.map(\.name).joined(separator: ",")
        if previous != manifest || !ProjectSettings.hasSetting(name: manifestKey) {
            ProjectSettings.setSetting(name: manifestKey, value: Variant(manifest))
            settingsChanged = true
        }
        guard settingsChanged else { return }
        let error = ProjectSettings.save()
        if error != .ok {
            GD.pushError("Cannot save SwiftGodot autoload settings: \(error)")
        }
    }
}
