#if os(macOS)
// We avoid Foundation on non-APple platforms to reduce the dependencies,
// but on MacOS, we can bring it.
import Foundation
#endif

public class EditorInterop {
    private static func loadHelp(xmlBytes: [UInt8]) {
        if let loadHelpWithLength = gi.editor_help_load_xml_from_utf8_chars_and_len {
            xmlBytes.withUnsafeBufferPointer { buffer in
                guard let base = buffer.baseAddress else { return }
                let ptr = UnsafeRawPointer(base).bindMemory(to: CChar.self, capacity: buffer.count)
                loadHelpWithLength(ptr, Int64(buffer.count))
            }
            return
        }

        guard let loadHelp = gi.editor_help_load_xml_from_utf8_chars else {
            return
        }

        var nullTerminated = xmlBytes.map { CChar(bitPattern: $0) }
        nullTerminated.append(0)
        nullTerminated.withUnsafeBufferPointer { buffer in
            loadHelp(buffer.baseAddress)
        }
    }

    //  Gets the path to the current GDExtension library.
    public static func getLibraryPath() -> String? {
        let res = GString()
        gi.get_library_path(extensionInterface.getLibrary(), &res.content)
        return GString.stringFromGStringPtr(ptr: &res.content)
    }

    /// Adds the Godot XML documentation to the editor at runtime
    public static func loadHelp(xmlString: String) {
        GD.print("Loading from \(getLibraryPath())")
        loadHelp(xmlBytes: Array(xmlString.utf8))
    }

    /// Adds the Godot XML documentation to the editor at runtime
    public static func loadHelp(buffer: [UInt8]) {
        loadHelp(xmlBytes: buffer)
    }

#if os(macOS)
    /// Adds the Godot XML documentation to the editor at runtime
    static func loadHelp(fromData data: Data) {
        loadHelp(xmlBytes: [UInt8](data))
    }
#endif

    // MARK: Documentation generated by the `@Godot` macro

    /// Registered classes that carry generated documentation, by Godot class name.
    private static var documentedClasses: [String: Object.Type] = [:]

    /// Classes whose generated documentation the editor already has.
    private static var loadedClassDocumentation: Set<String> = []

    /// Whether the editor accepts documentation, which is from the `.editor`
    /// initialization level until that level is deinitialized.
    private static var editorAcceptsDocumentation = false

    /// Records a registered class's generated documentation, loading it into the
    /// editor when the editor is ready for it.
    static func loadClassDocumentation(name: String, type: Object.Type) {
        guard type._editorDocumentation != nil else {
            return
        }
        documentedClasses[name] = type
        if editorAcceptsDocumentation {
            loadClassDocumentation(name: name)
        }
    }

    /// Loads the generated documentation of every registered class. Called when
    /// the extension reaches the `.editor` initialization level.
    static func loadRegisteredClassDocumentation() {
        editorAcceptsDocumentation = true
        for name in documentedClasses.keys.sorted() {
            loadClassDocumentation(name: name)
        }
    }

    /// Called when the `.editor` initialization level is deinitialized.
    static func stopLoadingClassDocumentation() {
        editorAcceptsDocumentation = false
        loadedClassDocumentation.removeAll()
    }

    /// Called when a class is unregistered; Godot drops its documentation, and
    /// it is loaded again if the class is registered again, as on a reload.
    static func forgetClassDocumentation(name: String) {
        documentedClasses.removeValue(forKey: name)
        loadedClassDocumentation.remove(name)
    }

    private static func loadClassDocumentation(name: String) {
        guard !loadedClassDocumentation.contains(name),
              let xml = documentedClasses[name]?._editorDocumentation else {
            return
        }
        loadedClassDocumentation.insert(name)
        loadHelp(xmlBytes: Array(xml.utf8))
    }

    public static func loadLibraryDocs() {
        guard let basePath = getLibraryPath() else {
            return
        }
#if os(macOS)
        let url = URL(fileURLWithPath: basePath)
        let parent = url.deletingLastPathComponent()
        let docs = parent.appending(components: "Resources", "doc_classes")
        if let contents = try? FileManager.default.contentsOfDirectory(at: docs, includingPropertiesForKeys: nil) {
            for file in contents {
                guard file.path().hasSuffix(".xml") else {
                    continue
                }
                if let contents = try? Data(contentsOf: file) {
                    loadHelp(fromData: contents)
                }
            }
        }
#else
        // MacOS has .frameworks that are convenient ways of distributing this, but
        // Windows and Linux do not, not sure what would be a good place to load
        // the docs from.
#endif
    }
}
